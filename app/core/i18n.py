_current = "zh_CN"


class I18n(QObject):
    languageChanged = Signal(str)

    def __init__(self, language: str = "zh_CN") -> None:
        super().__init__()
        self._current = language if language in TRANSLATIONS else "zh_CN"

    @property
    def current(self) -> str:
        return self._current

    def set_language(self, code: str) -> None:
        if code in TRANSLATIONS and code != self._current:
            self._current = code
            self.languageChanged.emit(code)

    def tr(self, text: str) -> str:
        return TRANSLATIONS.get(self._current, {}).get(text, text)


_i18n: I18n | None = None


def init_i18n(language: str) -> I18n:
    global _i18n
    if _i18n is None:
        _i18n = I18n(language)
    else:
        _i18n.set_language(language)
    return _i18n


def i18n() -> I18n:
    global _i18n
    if _i18n is None:
        _i18n = I18n()
    return _i18n


def tr(text: str) -> str:
    return i18n().tr(text)


def source_text(text: str) -> str:
    """把任意语言的文案反查为源文案，供已有控件在切换语言时同步。

    必须遍历所有语言字典：控件在切换前可能显示的是旧语言译文，而当前语言
    字典里并没有该译文（例如 en → zh_CN 时控件显示 "Settings"，zh_CN
    字典为空无法反查）。只查当前语言会导致弹窗/二级菜单停在旧语言。
    """
    if not text:
        return text
    # 先查当前语言（命中率最高且避免多语言同值歧义），再查其余语言
    current = i18n().current
    languages = [current, *(code for code in TRANSLATIONS if code != current)]
    for language in languages:
        for source, translated in TRANSLATIONS.get(language, {}).items():
            if translated == text:
                return source
    return text
